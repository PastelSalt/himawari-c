/** hwc graph, report ai-content, and ai setup, on a temporary copy of a project. */
import { cpSync, mkdtempSync, readFileSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { ProjectFs, stampAi } from "@himawari/tools";
import { afterAll, beforeAll, describe, expect, test, vi } from "vitest";
import { aiSetup, graph, report } from "./commands.js";

const ROOT = fileURLToPath(new URL("../../../", import.meta.url));
let dir = "";

/** Runs fn and returns what it wrote to stdout (console.log included). */
function capture(fn: () => number): string {
  let out = "";
  const write = vi.spyOn(process.stdout, "write").mockImplementation((s: string | Uint8Array) => {
    out += String(s);
    return true;
  });
  const log = vi.spyOn(console, "log").mockImplementation((...a: unknown[]) => {
    out += `${a.join(" ")}\n`;
  });
  try {
    expect(fn()).toBe(0);
  } finally {
    write.mockRestore();
    log.mockRestore();
  }
  return out;
}

beforeAll(() => {
  dir = mkdtempSync(join(tmpdir(), "hwc-cmd-"));
  cpSync(join(ROOT, "tests/conformance/cases/basic"), dir, { recursive: true });
});
afterAll(() => rmSync(dir, { recursive: true, force: true }));

describe("hwc commands", () => {
  test("graph prints Mermaid or JSON", () => {
    expect(capture(() => graph(dir, []))).toContain('s_ch1_hub -.->|"The festival."| s_talk_festival');
    const json = JSON.parse(capture(() => graph(dir, ["--format", "json"]))) as { entry: string };
    expect(json.entry).toBe("ch1_intro");
  });

  test("report ai-content counts AI-written and edited lines", () => {
    const fs = new ProjectFs(dir);
    stampAi(fs, "lines", new Map([["k3f9a1", "Good morning, [player_name]! You're late {b}again{/b}."], ["m1n2p3", "an older text"]]));
    const md = capture(() => report(dir, ["ai-content"]));
    expect(md).toContain("| Script lines (14) | 12 (86%) | 1 (7%) | 1 (7%) |");
    expect(md).toContain("no images, music, sound, or voices were generated by AI");
    const json = JSON.parse(capture(() => report(dir, ["ai-content", "--format", "json"]))) as { lines: Record<string, number> };
    expect(json.lines).toEqual({ human: 12, ai: 1, "ai-edited": 1 });
  });

  test("ai setup prints both clients' configs and writes .mcp.json", () => {
    const out = capture(() => aiSetup(dir, ["setup", "--write"]));
    expect(out).toContain("claude mcp add himawari --");
    expect(out).toContain("claude_desktop_config.json");
    const cfg = JSON.parse(readFileSync(join(dir, ".mcp.json"), "utf8")) as { mcpServers: { himawari: { args: string[] } } };
    expect(cfg.mcpServers.himawari.args.slice(1)).toEqual(["--project", dir]);
  });
});
