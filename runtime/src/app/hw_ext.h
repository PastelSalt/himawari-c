/*
 * Himawari-C: extension statements (rfcs/0007, plan §12 Tier B).
 *
 * A game adds a statement by declaring it in extensions/<name>.schema.json
 * and implementing it in C in a custom runtime build: list the C files in the
 * CMake cache variable HW_EXTENSIONS; each file <stem>.c defines
 * `void hw_ext_register_<stem>(void)`, which calls hw_register_statement().
 * Core checks every call against the schema, so a handler receives values of
 * the declared types, already validated.
 *
 * Saves and rollback: the VM remembers each statement's most recent call (the
 * first HW_VM_EXT_VALUES values) as part of what's on screen, and saves keep
 * it. After a load, a rewind, a reload, or a warp, the player calls restore()
 * with that call, so a statement that leaves something on screen (a tint, a
 * phone UI) shows it again without keeping any state of its own.
 */
#ifndef HW_EXT_H
#define HW_EXT_H

#include <SDL3/SDL.h>

#include <stdbool.h>
#include <stdint.h>

#include "hw_vm.h"

#define HW_EXT_MAX 32

typedef struct hw_ext_call {
    const hw_vm *vm;
    uint32_t ext;            /* XTNS index */
    const uint32_t *values;  /* one per parameter (for restore(): the first HW_VM_EXT_VALUES, the rest read as 0) */
    uint32_t count;          /* how many values `values` holds */
} hw_ext_call;

/* Values by parameter name. A name the statement doesn't have gives 0, false, or "". */
int32_t hw_ext_int(const hw_ext_call *c, const char *param);
bool hw_ext_bool(const hw_ext_call *c, const char *param);
/* A name-typed value: a character id, a position, a scene, an asset name, a transition, or a word. */
const char *hw_ext_word(const hw_ext_call *c, const char *param);
/* The text argument in the player's language, as markup ({b}…{/b}); "" when left out. Returns the length needed. */
size_t hw_ext_text(const hw_ext_call *c, char *buf, size_t cap);

typedef struct hw_ext_statement {
    const char *name;
    void *user;
    /* The statement runs. */
    void (*begin)(void *user, const hw_ext_call *call);
    /* Blocking statements: called every frame; return true when done. NULL means done at once. */
    bool (*update)(void *user, double dt);
    /* A click or the confirm button while this statement blocks the story. Return true if it used it. */
    bool (*click)(void *user);
    /* Ends a blocking statement now (the player skips, rewinds, loads, or quits to the title). */
    void (*finish)(void *user);
    /* After a load, a rewind, a reload, a warp, or a new start: show what the statement's most recent call left on
     * screen, at once (no animation). `last` is NULL when the statement hasn't run in this story. */
    void (*restore)(void *user, const hw_ext_call *last);
    /* Draws over the scene, under the textbox, every frame of play. Optional. `now` is in seconds of SDL_GetTicksNS(). */
    void (*draw)(void *user, SDL_Renderer *ren, float w, float h, double now);
    /* Whether what draw shows is still changing (an animation in progress). Optional: the player stops redrawing
     * while nothing moves (RA-6), and without this it keeps redrawing as long as a statement with draw has run. */
    bool (*animating)(void *user, double now);
} hw_ext_statement;

/* Registers a statement (copied). Returns false when the name is taken or the registry is full. */
bool hw_register_statement(const hw_ext_statement *s);
/* The handler registered for a name, or NULL. */
const hw_ext_statement *hw_ext_find(const char *name);
/* Registers every extension this runtime was built with (generated by CMake). */
void hw_ext_register_all(void);

#endif
